// Утилиты склонения числительных для русскоязычного UI.
// Правило: n % 10 определяет форму; исключения при n % 100 в диапазоне 11–14.
// Переиспользуются в «Мои заказы» (orders/page.tsx) и строке повтора (этап 20, план 03).

/**
 * Склонение слова «заказ»: 1 заказ / 2 заказа / 5 заказов.
 */
export function pluralOrders(n: number): string {
  if (n % 10 === 1 && n % 100 !== 11) return 'заказ';
  if ([2, 3, 4].includes(n % 10) && ![12, 13, 14].includes(n % 100))
    return 'заказа';
  return 'заказов';
}

